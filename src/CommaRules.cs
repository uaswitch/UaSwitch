namespace UaSwitch;

/// <summary>
/// Консервативні правила коми перед сполучниками («знаю що» → «знаю, що»).
/// Кома ставиться лише тоді, коли попереднє слово — звичайне слово, а не сполучник,
/// прийменник чи частка: «тому що», «для того щоб», «в якому», «поки що» не чіпаються.
/// </summary>
internal static class CommaRules
{
    private static readonly HashSet<string> Conjunctions = new()
    {
        "але", "проте", "однак", "щоб", "що",
        "який", "яка", "яке", "які", "якого", "якої", "якому", "якій", "яким", "якими", "яких",
        "котрий", "котра", "котре", "котрі", "котрого", "котрої", "котрому", "котрій", "котрим", "котрими", "котрих",
    };

    private static readonly HashSet<string> NoCommaAfter = new()
    {
        // сполучники та частки
        "і", "й", "та", "а", "але", "або", "чи", "ні", "не", "то", "бо", "ніж", "аніж", "тому", "того", "так",
        "лише", "тільки", "хоч", "хоча", "якщо", "коли", "де", "куди", "проте", "однак", "щоб", "що", "аби",
        "це", "оте", "все", "усе", "вже", "ще", "саме", "навіть", "аж", "от", "ось", "ото", "ну", "мов", "мовби",
        "наче", "неначе", "ніби", "нібито", "начебто", "мабуть", "адже", "тож", "отже", "також", "теж", "поки",
        "мало", "дещо", "хто", "дехто", "ніхто", "хтось", "кожен", "кожний", "чого", "через",
        "який", "яка", "яке", "які", "котрий", "котра", "котре", "котрі",
        // прийменники («в якому» — кома мала б стояти перед прийменником)
        "після", "перед", "для", "при", "з", "із", "зі", "зо", "в", "у", "во", "на", "до", "від", "од", "по", "за",
        "про", "без", "під", "над", "між", "поміж", "серед", "крім", "окрім", "замість", "біля", "коло", "щодо",
        "завдяки", "понад", "протягом", "впродовж", "навколо", "попри", "згідно", "відповідно", "внаслідок",
    };

    /// <summary>prev — попереднє слово (як на екрані), word — щойно набране слово.</summary>
    public static bool ShouldInsert(string? prev, string word)
    {
        if (prev == null || prev.Length == 0) return false;
        if (!Conjunctions.Contains(word.ToLowerInvariant())) return false;
        if (!char.IsLetter(prev[prev.Length - 1])) return false;      // уже є кома чи інший знак
        if (!prev.Any(c => c is >= 'Ѐ' and <= 'ӿ')) return false; // попереднє слово українське
        if (prev.Any(char.IsDigit)) return false;
        return !NoCommaAfter.Contains(prev.ToLowerInvariant());
    }
}
